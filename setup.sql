 room text not null, id integer not null, name text not null, total integer not null,
 done integer not null default 0, updated_at timestamptz not null default now(),
 primary key(room,id)
);
alter table public.farm_items enable row level security;
create policy "public read farm items" on public.farm_items for select to anon, authenticated using (true);
create policy "public insert farm items" on public.farm_items for insert to anon, authenticated with check (true);
create policy "public update farm items" on public.farm_items for update to anon, authenticated using (true) with check (true);
alter publication supabase_realtime add table public.farm_items;
